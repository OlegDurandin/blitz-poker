//! Regenerates `src/preflop_table.rs`:
//! `cargo run -p bot --release --example gen_preflop > crates/bot/src/preflop_table.rs`
//!
//! Heads-up all-in equity of each of the 169 starting-hand classes against a
//! uniformly random hand, by Monte Carlo.

use poker_core::card::full_deck;
use poker_core::rng::Rng;
use poker_core::{Card, Suit, hand_value};

const ITERATIONS: usize = 60_000;

fn main() {
    let mut rng = Rng::new(0x5EED_CAFE);
    println!("//! Generated by `examples/gen_preflop.rs`; do not edit by hand.");
    println!("//!");
    println!(
        "//! `EQUITY[hi][lo]`: heads-up equity vs a random hand, ranks 0 = deuce .. 12 = ace."
    );
    println!("//! `hi > lo` suited, `hi < lo` offsuit (indexed `[lo][hi]`), `hi == lo` pairs.");
    println!();
    println!("pub const EQUITY: [[f32; 13]; 13] = [");
    for row in 0..13u8 {
        let mut cells = Vec::new();
        for col in 0..13u8 {
            let (hi, lo, suited) = if row > col {
                (row, col, true)
            } else {
                (col, row, false)
            };
            let a = Card::new(hi, Suit::Spades);
            let b = Card::new(lo, if suited { Suit::Spades } else { Suit::Hearts });
            let deck: Vec<Card> = full_deck()
                .into_iter()
                .filter(|&c| c != a && c != b)
                .collect();
            let mut score = 0.0;
            let mut d = deck.clone();
            for _ in 0..ITERATIONS {
                for k in 0..7 {
                    let j = k + rng.below((d.len() - k) as u64) as usize;
                    d.swap(k, j);
                }
                let mine = hand_value(&[a, b, d[2], d[3], d[4], d[5], d[6]]);
                let theirs = hand_value(&[d[0], d[1], d[2], d[3], d[4], d[5], d[6]]);
                score += match mine.cmp(&theirs) {
                    std::cmp::Ordering::Greater => 1.0,
                    std::cmp::Ordering::Equal => 0.5,
                    std::cmp::Ordering::Less => 0.0,
                };
            }
            cells.push(format!("{:.4}", score / ITERATIONS as f64));
        }
        println!("    [{}],", cells.join(", "));
    }
    println!("];");
}
